def parse_details() -> dict[str, tuple[str, str]]:
    result: dict[str, tuple[str, str]] = {}
    for line in DETAILS_RAW.strip().splitlines():
        title, definition, example = [part.strip() for part in line.split("|", 2)]
        if not title or not definition or not example:
            raise ValueError(f"Некорректная строка: {line!r}")
        if LATIN.search(title + definition + example):
            raise ValueError(f"В публичном тексте осталась латиница: {line!r}")
        result[title.casefold()] = (definition, example)
    return result


def main() -> None:
    details = parse_details()
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    try:
        changed = 0
        missing = []
        rows = conn.execute(
            """
            SELECT t.id AS term_id, t.term_name, d.id AS definition_id
            FROM terms t
            JOIN definitions d ON d.term_id = t.id
            WHERE d.definition_text LIKE ?
               OR EXISTS (
                   SELECT 1 FROM examples e
                   WHERE e.definition_id = d.id
                     AND e.example_text LIKE ?
               )
            ORDER BY t.id
            """,
            (GENERIC_PREFIX + "%", "В рабочем чате%"),
        ).fetchall()
        for row in rows:
            item = details.get(row["term_name"].casefold())
            if not item:
                missing.append(row["term_name"])
                continue
            definition, example = item
            conn.execute(
                "UPDATE definitions SET definition_text = ?, style_note = 'жарг.' WHERE id = ?",
                (definition, row["definition_id"]),
            )
            conn.execute("DELETE FROM examples WHERE definition_id = ?", (row["definition_id"],))
            conn.execute(
                "INSERT INTO examples (definition_id, example_text) VALUES (?, ?)",
                (row["definition_id"], example),
            )
            changed += 1

        if missing:
            raise RuntimeError("Нет уточнений для терминов: " + ", ".join(missing))

        leftovers = conn.execute(
            """
            SELECT COUNT(*)
            FROM definitions d
            LEFT JOIN examples e ON e.definition_id = d.id
            WHERE d.definition_text LIKE ?
               OR e.example_text LIKE ?
            """,
            (GENERIC_PREFIX + "%", "В рабочем чате%"),
        ).fetchone()[0]
        if leftovers:
            raise RuntimeError(f"Остались шаблонные карточки: {leftovers}")

        latin_public = []
        for table, column in (
            ("terms", "term_name"),
            ("definitions", "definition_text"),
            ("examples", "example_text"),
        ):
            for row_id, text in conn.execute(f"SELECT id, {column} FROM {table}"):
                if text and LATIN.search(text):
                    latin_public.append((table, row_id, text))
        if latin_public:
            raise RuntimeError(f"В публичном тексте осталась латиница: {latin_public[:5]!r}")

        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

    print(f"Уточнено карточек: {changed}")


if __name__ == "__main__":
    main()
